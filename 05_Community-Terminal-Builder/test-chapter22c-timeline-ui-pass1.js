"use strict";
const fs=require("fs"),path=require("path"),assert=require("assert");
const root=path.resolve(__dirname,"..");
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const timelineHtml=read("07_Timeline/public/index.html");
const timelineCss=read("07_Timeline/public/timeline.css");
const timelineJs=read("07_Timeline/public/timeline.js");
const timelineShared=read("07_Timeline/public/style.css");
const landingShared=read("01_Landing-Page/public/style.css");
const pulseShared=read("06_Community-Pulse/public/style.css");
const whaleShared=read("02_Whale-Activity-Tracker/public/style.css");
const whaleCss=read("02_Whale-Activity-Tracker/public/whale.css");
const builderCss=read("05_Community-Terminal-Builder/public/style.css");
const generator=read("05_Community-Terminal-Builder/generator.js");
assert(timelineHtml.includes('class="module-subtitle">Community Timeline</div>'),"Timeline exact module subtitle missing");
assert(timelineHtml.indexOf('module-subtitle">Community Timeline')<timelineHtml.indexOf('class="online-status"'),"Timeline subtitle must be directly above ONLINE");
assert(timelineHtml.includes("portal-hero")&&timelineHtml.includes("portal-header-energy"),"Timeline must use canonical portal header");
assert(timelineHtml.includes('id="backToTop"'),"Timeline back-to-top missing");
assert(timelineShared===landingShared&&pulseShared===landingShared&&whaleShared===landingShared,"Landing/Whales/Pulse/Timeline must share exact canonical stylesheet");
assert(landingShared.includes("CPB canonical module-page header contract"),"Canonical header contract missing from shared stylesheet");
assert(!whaleCss.includes("Shared header remains the accepted Landing header"),"Whale page-specific header override must be removed");
assert(timelineCss.includes("timeline-overview-panel")&&timelineCss.includes("timeline-feed-panel"),"Timeline NEW UI panels missing");
assert(timelineJs.includes("Community Portal created")&&timelineJs.includes("Portal modules activated"),"Timeline starter milestones missing");
assert(timelineJs.includes('history.scrollRestoration="manual"'),"Timeline refresh-to-top missing");
assert(generator.includes("timeline: { createdAt: generatedAt, events: [] }"),"Generated config must carry Timeline creation timestamp");
assert(builderCss.includes("CPB deployment live-status alignment refinement")&&builderCss.includes("padding-left:16px"),"Deployment live-status alignment refinement missing");
console.log("✅ Timeline NEW UI + canonical header + CPB status refinement checks passed.");
